def get_masses(atomic_numbers):
    masses = []
    for atom in atomic_numbers:
        masses.append(elements[int(atom)][1])
    return np.array(masses) 





def check_atomic_numbers(atomic_numbers):
    check = atomic_numbers[0]
    for vec in atomic_numbers:
        is_equal = np.array_equal(check, vec)
        if not is_equal:
            print('ERROR: The atom types are not at the same order for all the structures!!')
            raise ValueError("Error in atomic numbers.")
    return atomic_numbers[0]
